// Union kiểu "settings.title" | "login.email" | ... — sai key báo lỗi tsc
// ngay lúc code, không phải runtime.
type PathsOf<T, Prefix extends string = ''> = {
  [K in keyof T & string]: T[K] extends string
    ? `${Prefix}${K}`
    : PathsOf<T[K], `${Prefix}${K}.`>;
}[keyof T & string];

export type TranslationKey = PathsOf<typeof en>;
